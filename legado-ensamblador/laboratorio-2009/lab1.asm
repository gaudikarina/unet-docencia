LIST		P=16F877
		INCLUDE	<P16F877.INC>
		RADIX	HEX
		ORG		0x00
		GOTO		INICIO
		ORG		0X04
		GOTO		INICIO
INICIO	BCF		STATUS,RP1
		BSF		STATUS,RP0
		MOVLW	b'11111111'
		MOVWF	TRISB
		CLRF		TRISC
		BCF		STATUS,RP0
		CLRF		PORTB
		CLRF		PORTC
LAZO		BTFSC	PORTB,1
		GOTO		EDO1O2	
		GOTO 	EDO3O4
EDO1O2	BTFSC	PORTB,0
		GOTO		EDO1
		GOTO		EDO2
EDO3O4	BTFSC	PORTB,0
		GOTO		EDO3
		GOTO		EDO4
EDO1		MOVLW	B'00000000'
		MOVWF	PORTC
		MOVLW	B'11111111'
		MOVWF	PORTC
		GOTO		LAZO
EDO2		MOVLW	B'11110000'
		MOVWF	PORTC
		MOVLW	B'00001111'
		MOVWF	PORTC
		GOTO		LAZO
EDO3		MOVLW	B'10101010'
		MOVWF	PORTC
		MOVLW	B'01010101'
		MOVWF	PORTC
		GOTO	LAZO
EDO4		MOVLW	B'11000011'
		MOVWF	PORTC
		MOVLW	B'00111100'
		MOVWF	PORTC
		GOTO		LAZO
		END
