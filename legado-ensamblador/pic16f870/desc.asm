;**********************CONTANDOR DESCENDENTE DECIMAL*********************
	
	LIST	P=16C74
	RADIX	HEX
;******DEFINICION DE REGISTROS ESPECIALES Y DE PROPOSITO GENERAL********
STATUS	EQU	0x03	;DEFINICION DEL REGISTRO ESPECIAL DE ESTADO
CONT	EQU	0x21	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
DIEZ	EQU	0X22	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
BAND	EQU	0X23	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
SESEN	EQU	0X24	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
MOS	EQU	0X25	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
LSB	EQU	0X26
MSB	EQU	0X27
;**************************INICIO DEL PROGRAMA***************************
	ORG	0

INICIO
	MOVLW	0X99
	MOVWF	CONT	;CONT=99
	MOVLW	0X0F
	MOVWF	DIEZ	;DIEZ=0F
	MOVLW	0XF0
	MOVWF	SESEN	;SESEN=F0
	MOVLW	0X06
	MOVWF	LSB
	MOVLW	0X60
	MOVWF	MSB
CUENTA
	CALL	MOSTRAR	;LLAMADO A RUTINA QUE GUARDA EL VALOR DEL CONTADOR EN EL REGSITRO MOS
	MOVF	CONT,0
	DECF	CONT,1	;CONT=CONT-1	
	MOVF	CONT,0	;CHEQUEA SI LOS 4 LSB 
	ANDLW	0X0F	;DEL REGISTRO CONT SON 
	MOVWF	BAND	;MENORES A DIEZ DECIMAL
	MOVF	DIEZ,0	;(0A HEX)
	SUBWF	BAND,0	;Y REALIZA EL AJUSTE DECIMAL
	BTFSS	STATUS,2;SI ES MAYOR
	GOTO	CUENTA	;CUENTA SI ES MENOR
	GOTO	DOS	;AJUSTE SI ES MAYOR
DOS
	MOVF	LSB,0	;W=06
	SUBWF	CONT,1	;AJUSTE DECIMAL A LOS 4 LSB
	MOVF	CONT,0
	ANDLW	0XF0	;CHEQUEA SI LOS 4 MSB 
	MOVWF	BAND	;DEL REGISTRO CONT SON 
	MOVF	SESEN,0	;MENORES A A0 HEX
	SUBWF	BAND,0	;Y REALIZA EL AJUSTE DECIMAL
	BTFSS	STATUS,2;
	GOTO	CUENTA	;CUENTA SI ES MENOR A A0h
	MOVF	MSB,0	;W=60
	SUBWF	CONT,1	;AJUSTE SI ES MAYOR A A0h	
	GOTO	CUENTA
MOSTRAR
	MOVF	CONT,0	;GUARDA EN MOS EL VALOR DEL CONT EN DECIMAL
	MOVWF	MOS
	RETURN
	END		;FIN DEL PROGRAMA
	
