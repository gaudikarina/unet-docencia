;**********************SUMA DECIMAL DE DOS DATOS INTRODUCIDOS POR PUERTO(OTRA FORMA NIBBLE A NIBBLE)*********************
	
	LIST	P=16C74
	RADIX	HEX
;******DEFINICION DE REGISTROS ESPECIALES Y DE PROPOSITO GENERAL********
STATUS	EQU	0x03	;DEFINICION DEL REGISTRO ESPECIAL DE ESTADO
PORTB	EQU	0X06
TRISB	EQU	0X86
PORTC	EQU	0X07
PORTD	EQU	0X08
TRISC	EQU	0X87
TRISD	EQU	0X88
OP1		EQU	0x21	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
OP2		EQU	0X22	;DEFINICION DEL REGISTRO DE PROPOSITO GENERAL 
MSB		EQU	0X23
M9		EQU	0X26
LSB		EQU	0X24
RESUL	EQU	0X25
M9M		EQU	0X27
;**************************INICIO DEL PROGRAMA***************************
	ORG	0
	BSF	STATUS,5	;BANCO 01
	MOVLW	0XFF		
	MOVWF	TRISC		;CONFIGURA PUERTO C COMO ENTRADA
	MOVWF	TRISB		;CONFIGURA PUERTO B COMO ENTRADA
	MOVLW	0X00
	MOVWF	TRISD
	BCF	STATUS,5	;BANCO 0
INICIO
	MOVLW	0X0A
	MOVWF	M9
	MOVLW	0XA0
	MOVWF	M9M
	MOVF	PORTB,0		;LEE PUERTO B Y GUARDA EN W
	MOVWF	OP1			;OP1=W
	MOVF	PORTC,0		;LEE PUERTO C Y GUARDA EN W
	MOVWF	OP2			;OP2=W
	CALL	SUM_LSB
	CALL	SUM_MSB
	MOVF	LSB,0
	ADDWF	MSB,0
	MOVWF	RESUL
	MOVWF	PORTD		;MUESTRA EL RESULTADO POR PUERTO D
	GOTO	INICIO
SUM_LSB
	MOVF	OP1,0
	ANDLW	0X0F
	MOVWF	LSB
	MOVF	OP2,0
	ANDLW	0X0F
	ADDWF	LSB,1
	CALL 	AJUS_DEC
	RETURN
SUM_MSB
	MOVF	OP1,0
	ANDLW	0XF0
	MOVWF	MSB
	MOVF	OP2,0
	ANDLW	0XF0
	ADDWF	MSB,1
	BTFSS	STATUS,0
	CALL 	AJUS_DEC_M
	MOVF	MSB,0
	ADDLW	0X60
	MOVWF	MSB
	RETURN
AJUS_DEC
	MOVF	M9,0
	SUBWF	LSB,0
	BTFSS	STATUS,0
	RETURN
	MOVF	LSB,0
	ADDLW	0X06
	MOVWF	LSB
	RETURN
AJUS_DEC_M
	MOVF	M9M,0
	SUBWF	MSB,0
	BTFSS	STATUS,0
	RETURN
	MOVF	MSB,0
	ADDLW	0X60
	MOVWF	MSB
	RETURN
	END
