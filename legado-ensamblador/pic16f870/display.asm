;**********************DISPLAY SIETE SEGMENTOS*********************
; DISPLAY 7 SEGMENTOS CONECTADO AL PUERTO B SE VISUALIZA LA CANTIDAD
; LEIDA POR PUERTO C EN HEXADECIMAL	
	LIST	P=16C74
	RADIX	HEX
;******DEFINICION DE REGISTROS ESPECIALES Y DE PROPOSITO GENERAL********
PCL	EQU	0X02
STATUS	EQU	0x03	;DEFINICION DEL REGISTRO ESPECIAL DE ESTADO
PORTB	EQU	0X06
TRISB	EQU	0X86
PORTC	EQU	0X07
TRISC	EQU	0X87
;**************************INICIO DEL PROGRAMA***************************
	ORG	0
	BSF	STATUS,5	;BANCO 01
	MOVLW	0X0F		
	MOVWF	TRISC		;CONFIGURA PUERTO C COMO ENTRADA (4 LSB)
	CLRF	TRISB		;CONFIGURA PUERTO B COMO SALIDA
	BCF	STATUS,5	;BANCO 0
INICIO
	MOVF	PORTC,0		;LEE LA ENTRADA Y GUARDA EN W
	ANDLW	0X0F		;MASCARA PARA QUEDARSE CON LA ENTRADA DEL NIBBLE BAJO
	CALL	BIN_7SEG	;CONVIERTE EL VALOR BINARIO A CODIGO 7 SEGMENTOS
	MOVWF	PORTB		;MUESTRA EL RESULTADO POR PUERTO B
	GOTO	INICIO
	
BIN_7SEG
	ADDWF	PCL,1
TABLA	RETLW	3F	;CODIGO PARA EL "0"
	RETLW	06	;CODIGO PARA EL "1"
	RETLW	5B	;CODIGO PARA EL "2"
	RETLW	4F	;CODIGO PARA EL "3"
	RETLW	66	;CODIGO PARA EL "4"
	RETLW	6D	;CODIGO PARA EL "5"
	RETLW	7D	;CODIGO PARA EL "6"
	RETLW	07	;CODIGO PARA EL "7"
	RETLW	7F	;CODIGO PARA EL "8"
	RETLW	67	;CODIGO PARA EL "9"
	RETLW	77	;CODIGO PARA EL "A"
	RETLW	7C	;CODIGO PARA EL "B"
	RETLW	39	;CODIGO PARA EL "C"
	RETLW	5E	;CODIGO PARA EL "D"
	RETLW	79	;CODIGO PARA EL "E"
	RETLW	71	;CODIGO PARA EL "F"
	END
