	include <P16F84A.INC>
	LIST	P=16F84A

CONTA	EQU	0X0D
CONTB	EQU	0X0C
CONTC	EQU 0X0E
	
	ORG	0H
	GOTO	INICIO
	
	ORG	4H
	GOTO	SERV_INT

INICIO
	BSF		STATUS,RP0
	BSF		TRISB,6
	BSF		TRISB,7
	BCF		TRISB,2
	MOVLW	B'10001000'
	MOVWF	INTCON
	BCF		STATUS,RP0
	BCF		PORTB,2
PRINCIPAL
	GOTO	PRINCIPAL
SERV_INT
	BTFSS	INTCON,RBIF
	RETFIE
	BCF		INTCON,RBIF
	BTFSC	PORTB,6
	GOTO	PITIDO_CORTO
	BTFSC	PORTB,7
	GOTO	PITIDO_LARGO
	RETFIE
PITIDO_LARGO
	BSF		PORTB,2
	CALL	RETARDO_LARGO
	BCF		PORTB,2
	CALL	RETARDO_LARGO
PITIDO_CORTO
	BSF		PORTB,2
	CALL	RETARDO
	BCF		PORTB,2
	CALL	RETARDO
	RETFIE
RETARDO_LARGO
	MOVLW	0X05
	MOVWF	CONTC
TRES
	MOVLW	0XFF
	MOVWF	CONTB
DOS
	MOVLW	0XFF
	MOVWF	CONTA
UNO
	DECFSZ	CONTA,F
	GOTO	UNO
	DECFSZ	CONTB,F
	GOTO	DOS
	DECFSZ	CONTC,F
	GOTO	TRES
	RETURN
RETARDO
	MOVLW	0XFF
	MOVWF	CONTB
LAZO
	MOVLW	0XFF
	MOVWF	CONTA
SALTO
	DECFSZ	CONTA,F
	GOTO	SALTO
	DECFSZ	CONTB,F
	GOTO	LAZO
	RETURN
FIN
	END