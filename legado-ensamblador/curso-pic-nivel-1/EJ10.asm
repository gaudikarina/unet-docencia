	include <P16F84A.INC>
	LIST	P=16F84A

A1	EQU	0x0C	

	ORG	0H
	GOTO	INICIO
	
	ORG	4H
	GOTO	SERV_INT

INICIO
	BSF		STATUS,RP0
	BCF		TRISB,1
	BSF		TRISB,0
	MOVLW	B'10010000'
	MOVWF	INTCON
	BCF		OPTION_REG,INTEDG
	BCF		STATUS,RP0
	CLRF	PORTB
	CLRF	A1
PRINCIPAL
	GOTO	PRINCIPAL
SERV_INT
	BTFSS	INTCON,INTF
	RETFIE
	BCF		INTCON,INTF
	BTFSS	A1,0
	GOTO	CERO
	GOTO	UNO
CERO
	INCF	A1,F
	BSF		PORTB,1
	RETFIE
UNO
	INCF	A1,F
	BCF		PORTB,1
	RETFIE
FIN
	END