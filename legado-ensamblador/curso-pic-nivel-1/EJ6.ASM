	include <P16F84A.INC>
	LIST	P=16F84A

CONTA	EQU 0X0C
CONTB	EQU	0X0D
CONTC	EQU	0X0E
DER		EQU	0X0F
IZQ		EQU	0X10	
	
	ORG	0H
	
INICIO
	BSF		STATUS,RP0
	CLRF	TRISB
	BCF		STATUS,RP0
	CLRF	PORTB
PRINCIPAL
	MOVLW	.5
	MOVWF	CONTC
PARPADEO
	MOVLW	0XFF
	MOVWF	PORTB
	CALL	RETARDO
	CLRF	PORTB
	CALL	RETARDO
	DECFSZ	CONTC,F
	GOTO	PARPADEO
	MOVLW	0X80
	MOVWF	DER
DERECHA
	MOVF	DER,W
	MOVWF	PORTB
	CALL	RETARDO
	RRF		DER,F
	BTFSS	STATUS,C
	GOTO	DERECHA
	BCF		STATUS,C
	MOVLW	0X01
	MOVWF	IZQ
IZQUIERDA
	MOVF	IZQ,W
	MOVWF	PORTB
	CALL	RETARDO
	RLF		IZQ,F
	BTFSS	STATUS,C
	GOTO	IZQUIERDA
	GOTO	PRINCIPAL
RETARDO
	MOVLW	0XFF
	MOVWF	CONTB
DOS
	MOVLW	0XFF
	MOVWF	CONTA
UNO
	DECFSZ	CONTA,F
	GOTO	UNO
	DECFSZ	CONTB,F
	GOTO	DOS
	RETURN
FIN
	END