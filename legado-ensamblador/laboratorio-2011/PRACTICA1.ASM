	LIST P=16F877
	INCLUDE <P16F877.INC>
	RADIX	HEX
VII	EQU	0X20
VID	EQU	0X21
VIP	EQU	0X22
VIN	EQU	0X23
	ORG 0X00
	GOTO	INICIO
	ORG	0X04
	GOTO	INICIO
INICIO
	CALL	CPUERTO
	CALL	IVALOR
LAZO
	CALL	CONTROL
	GOTO LAZO
CONTROL
	MOVF	PORTA,W
	CALL	TABLA
	MOVWF	PORTB
	RETURN
CPUERTO
	BCF	STATUS,RP1
	BSF	STATUS,RP0
	CLRF TRISB
	MOVLW	H'FF'
	MOVWF	TRISA
	MOVLW	D'007'
	MOVWF	ADCON1
	BCF		STATUS,RP0
	RETURN
IVALOR
	MOVLW	B'10000000'
	MOVWF	VID
	MOVLW	B'00000001'
	MOVWF	VII
	MOVLW	B'00001111'
	MOVWF	VIN
	MOVLW	B'01010101'
	MOVWF	VIP
	RETURN
TABLA
	ADDWF	PCL,F
	GOTO	ROTA_I
	GOTO	ROTA_D
	GOTO	PARIMP
	GOTO	NIBLE
	CLRF	PORTB
	RETURN
	
ROTA_I
	BCF		STATUS,C
	RLF		VII,F
	BTFSC	STATUS,C
	RLF		VII,F
	MOVF	VII,W
	RETURN

ROTA_D
	BCF		STATUS,C
	RRF		VID,F
	BTFSC	STATUS,C
	RRF		VID,F
	MOVF	VID,W
	RETURN
PARIMP
	COMF	VIP,F
	MOVF	VIP,W
	RETURN
NIBLE
	SWAPF	VIN,F
	MOVF	VIN,W
	RETURN
	
	END
	