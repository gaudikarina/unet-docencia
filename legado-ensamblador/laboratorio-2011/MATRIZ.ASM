	INCLUDE <P16F877.INC>
	LIST P=16F877
	
EP		EQU 0X020
EI		EQU	0X21	
LETRA	EQU	0X22
CONT	EQU	0X23
EP0		EQU	0X24
EP1		EQU	0X25
A1		EQU	0X26
	
	ORG	0
	GOTO	CONF
	ORG	4
	GOTO	SERV_INT

CONF
	BCF	STATUS,RP1
	BSF	STATUS,RP0
	CLRF	TRISC
	CLRF	TRISD
	MOVLW	0XF0
	MOVWF	TRISB
	BCF		STATUS,RP0
	MOVLW	B'10001000'
	MOVWF	INTCON

	CLRF	EI
	CLRF	EP
	MOVF	PORTB,W
	ANDLW	0X30
	MOVWF	EP
	SWAPF	EP,F
	CLRF	PORTD
	CLRF	PORTC
	CLRF	LETRA
INICIO
	CALL	MOSTRAR
	GOTO	INICIO
SERV_INT
	BTFSS	INTCON,RBIF
	RETFIE
	MOVF	PORTB,W
	ANDLW	0X30
	MOVWF	EI
	SWAPF	EI,F
	MOVF	EI,W
	SUBWF	EP,W
	BTFSS	STATUS,Z
	GOTO	DIFERENTES
	CLRF	LETRA
	CLRF	PORTD
	BCF		INTCON,RBIF
	RETFIE
DIFERENTES
	BCF		INTCON,RBIF
	MOVF	EP,W
	ANDLW	0X01
	MOVWF	EP0
	MOVF	EI,W
	ANDLW	0X01
	SUBWF	EP0,W
	BTFSS	STATUS,Z
	GOTO	LETRA4
	MOVF	EP,W
	ANDLW	0X02
	MOVWF	EP1
	MOVF	EI,W
	ANDLW	0X02
	SUBWF	EP1,W
	BTFSS	STATUS,Z
	GOTO	LETRA5
	GOTO	SALIR
LETRA4
	BTFSS	EI,0
	GOTO	T
	GOTO	E
LETRA5
	BTFSS	EI,1
	GOTO	N
	GOTO	U
SALIR
	MOVF	EI,W
	MOVWF	EP
	RETFIE
U
	MOVLW	0X01
	MOVWF	LETRA
	GOTO	SALIR
N
	MOVLW	0X02
	MOVWF	LETRA
	GOTO	SALIR
E
	MOVLW	0X03
	MOVWF	LETRA
	GOTO	SALIR
T
	MOVLW	0X04
	MOVWF	LETRA
	GOTO	SALIR
MOSTRAR
	MOVF	LETRA,W
	ADDWF	PCL,F
	RETURN
	GOTO	LETU
	GOTO	LETN
	GOTO	LETE
	GOTO	LETT
LETU
	BCF		STATUS,C
	MOVLW	01H
	MOVWF	PORTD
	MOVLW	0FFH
	MOVWF	PORTC
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	0C0H
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	0FFH
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	RETURN
LETN
	BCF		STATUS,C
	MOVLW	01H
	MOVWF	PORTD
	MOVLW	0FFH
	MOVWF	PORTC
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	06H
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	0CH
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	18H
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	30H
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	0FFH
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	RETURN
LETE
	BCF		STATUS,C
	MOVLW	01H
	MOVWF	PORTD
	MOVLW	0FFH
	MOVWF	PORTC
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	0DBH
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	MOVLW	0C3H
	MOVWF	PORTC
	RLF		PORTD,F
	CALL	RETARDO
	RLF		PORTD,F
	CALL	RETARDO
	CLRF	PORTC
	RlF		PORTD,F
	CALL	RETARDO
	RETURN
LETT
	BCF		STATUS,C
	MOVLW	01H
	MOVWF	PORTD
	MOVLW	03H
	MOVWF	PORTC
	nop
	CALL	RETARDO
	RLF		PORTD,F
	nop
	CALL	RETARDO
	RLF		PORTD,F
	nop
	CALL	RETARDO
	MOVLW	0FFH
	MOVWF	PORTC
	RLF		PORTD,F
	nop
	CALL	RETARDO
	RLF		PORTD,F
	nop
	CALL	RETARDO
	MOVLW	03H
	MOVWF	PORTC
	RLF		PORTD,F
	nop
	CALL	RETARDO
	RLF		PORTD,F
	nop
	CALL	RETARDO
	RLF		PORTD,F
	nop
	CALL	RETARDO
	nop
	RETURN
RETARDO
	MOVLW	D'3'
	MOVWF	CONT
LAZO
	MOVLW	D'20'
	MOVWF	A1
BUCLE
	NOP
	DECFSZ	A1,F
	GOTO	BUCLE
	DECFSZ	CONT,F
	GOTO	LAZO
	RETURN
	END
	
		
	